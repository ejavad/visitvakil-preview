import { chromium } from "playwright";
const browser = await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:390,height:844}});
const errors=[];
page.on("pageerror",e=>{errors.push(e.message);console.error("JS_ERROR",e.stack||e.message)});
page.on("console",m=>{if(m.type()==="error")console.error("CONSOLE_ERROR",m.text())});
await page.goto("http://127.0.0.1:8765/lawyer.html",{waitUntil:"load"});
console.log("IDS",await page.evaluate(()=>["offer-count","nav-offer-count","lawyer-list-title","ready","note","cases","support-list","support-panel"].map(id=>[id,!!document.getElementById(id)])));console.log("INITIAL",{tab:await page.locator("#workspace").getAttribute("data-lawyer-tab"),buttons:await page.locator("[data-lawyer-tab]").count(),hidden:await page.locator("#support-panel").getAttribute("hidden")});
await page.locator('[data-lawyer-tab="support"]').click();
console.log("AFTER_SUPPORT",{tab:await page.locator("#workspace").getAttribute("data-lawyer-tab"),hidden:await page.locator("#support-panel").getAttribute("hidden"),visible:await page.locator("#support-new").isVisible(),listVisible:await page.locator("#support-list").isVisible(),errors});
if(!await page.locator("#support-new").isVisible())throw Error("FOOTER_SUPPORT_NOT_VISIBLE");
await page.locator("#support-new").click();
await page.locator("#support-subject").fill("تست ثبت تیکت");
await page.locator("#support-body").fill("توضیح اولیه تست");
await page.locator('#support-form button[type="submit"]').click();
await page.waitForTimeout(100);
console.log("AFTER_CREATE",{tab:await page.locator("#workspace").getAttribute("data-lawyer-tab"),chatOpen:await page.locator("#workspace").getAttribute("class"),messages:await page.locator("#messages").innerText(),rows:await page.locator("#support-list .thread").count(),composer:await page.locator("#send").isVisible(),errors});
if(!await page.locator("#send").isVisible())throw Error("CHAT_COMPOSER_NOT_VISIBLE_AFTER_CREATION");
await page.locator("#body").fill("پیام دوم تست");
await page.locator('#send button[type="submit"]').click();
if(!await page.locator("#messages").getByText("پیام دوم تست").count())throw Error("SEND_MESSAGE_FAILED");
await page.locator("#lawyer-back").click();
console.log("AFTER_BACK",{listVisible:await page.locator("#support-list").isVisible(),rows:await page.locator("#support-list .thread").count()});
if(!await page.locator("#support-list .thread").count())throw Error("SAVED_TICKET_NOT_IN_LIST");
await page.locator("#support-list .thread").first().click();
if(!await page.locator("#messages").getByText("پیام دوم تست").count())throw Error("REOPEN_CHAT_HISTORY_FAILED");
console.log("PASS");
await browser.close();